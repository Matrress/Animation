// The Visual Asset Registry tool (the registry is data ABOUT assets; Ecwid still owns the photographs).
//
//   node tools/asset-registry.mjs from-legacy products/botanic.config.js --model botanic --out products/botanic.assets.js
//   node tools/asset-registry.mjs from-manifest products/x.media.js --model x --out products/x.assets.js
//   node tools/asset-registry.mjs check products/botanic.assets.js [--models botanic,placeholder]
//
// from-legacy   the model config's `media: [...]` list (exact URLs taken from the source description) as registry assets.
// from-manifest an existing media manifest (products/<model>.media.js, the gallery's format) as registry assets.
// check         validates a registry against schema/ddtv-schema.js.
// Nothing here fetches, uploads or invents an address: every URL comes from the file it converts.
import { createRequire } from 'node:module';
import { writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadScripts, loadAssetsModule } from './lib-load.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(import.meta.url);
const schema = require(join(root, 'schema', 'ddtv-schema.js'));
const [cmd, file, ...rest] = process.argv.slice(2);
const flag = (n) => { const i = rest.indexOf('--' + n); return i >= 0 ? rest[i + 1] : undefined; };
const usage = () => { console.error('usage: node tools/asset-registry.mjs <from-legacy|from-manifest|check> <file> [--model id] [--out file] [--models a,b]'); process.exit(2); };
if (!cmd || !file) usage();

function emit(model, assets) {
  const reg = { version: 1, galleryOrder: 'ecwid', assets };
  const res = schema.validateAssets(reg, { knownModels: [model] });
  if (res.errors.length) { console.error('The converted registry is not valid:'); res.errors.forEach((x) => console.error('  ' + x.path + ': ' + x.message)); process.exit(1); }
  const out = flag('out');
  const body = `/* Visual Asset Registry for "${model}": generated by tools/asset-registry.mjs. Data about assets; Ecwid owns the photographs.\n   Every address was copied from the source it was converted from. Review the roles and visibility, then commit. */\n(function (global) {\n  'use strict';\n  global.DDTV_ASSETS = global.DDTV_ASSETS || {};\n  global.DDTV_ASSETS[${JSON.stringify(model)}] = ${JSON.stringify(reg, null, 2)};\n})(window);\n`;
  if (out) { writeFileSync(out, body); console.log(`Wrote ${out}: ${assets.length} asset(s) for "${model}"`); }
  else console.log(body);
}

const model = flag('model');
if (cmd === 'from-legacy') {
  if (!model) usage();
  const win = loadScripts(resolve(file));
  const cfg = Object.values(win.DDTV_PRODUCTS).find((p) => p.id === model);
  if (!cfg) { console.error(`No model "${model}" in ${file}`); process.exit(1); }
  emit(model, loadAssetsModule(root).fromLegacyMedia(model, cfg.media));
} else if (cmd === 'from-manifest') {
  if (!model) usage();
  const win = loadScripts(resolve(file));
  const cfg = Object.values(win.DDTV_PRODUCTS).find((p) => p.id === model);
  const man = cfg && cfg.mediaManifest;
  if (!man || !man.images) { console.error(`No media manifest for "${model}" in ${file} (it is null until one is generated)`); process.exit(1); }
  const assets = man.images.map((m, i) => ({
    id: `${model}-photo-${String(i + 1).padStart(3, '0')}`, type: 'image', role: m.isMain ? 'main' : (m.customerGallery === false ? 'educational' : 'gallery'),
    scope: 'model', products: [model], status: 'active', ecwid: m.id ? { productId: man.productId, mediaId: String(m.id) } : undefined,
    urls: { 160: m.image160pxUrl, 400: m.image400pxUrl, 800: m.image800pxUrl, 1500: m.image1500pxUrl, original: m.imageOriginalUrl },
    alt: m.alt || '', width: m.width, height: m.height, categories: m.category ? [m.category] : [], tags: [], priority: 0, usedIn: m.usedIn || [],
    visibility: { gallery: m.customerGallery !== false }
  })).map((a) => JSON.parse(JSON.stringify(a)));
  emit(model, assets);
} else if (cmd === 'check') {
  const win = loadScripts(resolve(file));
  let bad = 0;
  for (const [name, reg] of Object.entries(win.DDTV_ASSETS)) {
    const known = (flag('models') || name).split(',');
    const res = schema.validateAssets(reg, { knownModels: known });
    console.log(`${name}: ${reg.assets.length} asset(s), ${res.errors.length} error(s), ${res.warnings.length} warning(s)`);
    res.errors.forEach((x) => console.log('  ERROR   ' + x.path + ': ' + x.message));
    res.warnings.forEach((x) => console.log('  warning ' + x.path + ': ' + x.message));
    bad += res.errors.length;
  }
  process.exit(bad ? 1 : 0);
} else usage();
