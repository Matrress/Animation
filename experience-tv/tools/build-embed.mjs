// Builds the files for a real store test (Ecwid product page):
//
//   dist/embed/botanic-tv.js              one self-starting file; upload it to the web host
//   dist/embed/ecwid-loader.js            JS to paste where the store takes JavaScript (loads the file)
//   dist/embed/ecwid-snippet.html         the same as one <script> tag, where the store takes HTML
//   dist/embed/ecwid-snippet-sri.html     the tag with Subresource Integrity (optional, see DEPLOYMENT.md)
//   dist/embed/botanic-description.html   the product description to paste into the test product
//   dist/embed/test-page.html             offline page with a SIMULATED Ecwid, to check the embed
//   dist/embed/MANIFEST.txt               sizes, hashes and the files' dependencies
//
//   node tools/build-embed.mjs
//
// The embed does nothing on other products: the engine starts only for a
// product id listed in products/botanic.config.js (productIds).
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (p) => readFileSync(join(root, p), 'utf8');
const outDir = join(root, 'dist', 'embed');
mkdirSync(outDir, { recursive: true });
const sha = (alg, text, enc) => createHash(alg).update(text).digest(enc);

const css = read('engine/ddtv-engine.css') + '\n' + read('engine/ddtv-scenes.css');
const config = read('products/botanic.config.js');
const zones = read('products/botanic.zones.js');
const engine = read('engine/ddtv-engine.js');
const scenes = read('engine/ddtv-scenes.js');
const description = read('source/botanic-original-description.html');

// The embed. Loading order (all inside one file, one function scope):
//   1. ?ddtv=off check (nothing is created when it is set)
//   2. Chillax font link + the styles (<style id="ddtv-styles">)
//   3. product data (config + seven-zone drawing)
//   4. engine, then scenes
//   5. start once Ecwid's storefront API is available
const embed = `/* Botanic Experience TV: store embed (generated by tools/build-embed.mjs).
   Starts only on the products listed in its config. Leaves the store's own
   options, price and checkout untouched. Add ?ddtv=off to a page address to
   switch it off completely. */
(function () {
  if (/[?&]ddtv=off/.test((window.location && window.location.search) || '')) return;
  if (window.__ddtvEmbedLoaded) return;
  window.__ddtvEmbedLoaded = true;

  var CSS = ${JSON.stringify(css)};
  var head = document.head || document.getElementsByTagName('head')[0] || document.documentElement;

  function add(tag, attrs) {
    var node = document.createElement(tag);
    for (var k in attrs) node.setAttribute(k, attrs[k]);
    head.appendChild(node);
    return node;
  }

  if (!document.getElementById('ddtv-font')) {
    add('link', { rel: 'preconnect', href: 'https://api.fontshare.com' });
    add('link', { id: 'ddtv-font', rel: 'stylesheet', href: 'https://api.fontshare.com/v2/css?f[]=chillax@300,400,500,600,700&display=swap' });
  }
  var style = document.getElementById('ddtv-styles') || add('style', { id: 'ddtv-styles' });
  style.textContent = CSS;

  /* ---- product data (botanic.config.js + botanic.zones.js) ---- */
${config}
${zones}

  /* ---- engine ---- */
${engine}

  /* ---- scenes ---- */
${scenes}

  /* ---- start once Ecwid's storefront API is there (about 15 s at most) ---- */
  var tries = 0;
  (function wait() {
    if (window.Ecwid && window.Ecwid.OnPageLoaded && window.DDTV) { window.DDTV.boot(); return; }
    if (++tries < 150) setTimeout(wait, 100);
  })();
})();
`;
writeFileSync(join(outDir, 'botanic-tv.js'), embed);

const sha384 = sha('sha384', embed, 'base64');
const sha256hex = sha('sha256', embed, 'hex');
const ver = sha256hex.slice(0, 10);
const URL_HINT = 'https://YOUR-SITE.example/PATH/botanic-tv.js';

// For a field that takes JavaScript (not HTML): loads the file once.
writeFileSync(join(outDir, 'ecwid-loader.js'), `/* Botanic Experience TV loader. Replace the address, keep ?v=${ver} (it refreshes the cache). */
(function () {
  if (/[?&]ddtv=off/.test(location.search) || window.__ddtvLoader) return;
  window.__ddtvLoader = true;
  var s = document.createElement('script');
  s.src = '${URL_HINT}?v=${ver}';
  s.async = true;
  document.head.appendChild(s);
})();
`);

// For a field that takes HTML.
writeFileSync(join(outDir, 'ecwid-snippet.html'), `<!-- Botanic Experience TV: one line. Replace the address; keep ?v=${ver} (it refreshes the cache). -->
<script src="${URL_HINT}?v=${ver}" async></script>
`);

// Optional: Subresource Integrity. It needs the host to send Access-Control-Allow-Origin, and the host
// must serve the file byte for byte (no minifying or combining plugin). See DEPLOYMENT.md.
writeFileSync(join(outDir, 'ecwid-snippet-sri.html'), `<!-- OPTIONAL: with Subresource Integrity. Use it only after the two checks in DEPLOYMENT.md pass,
     otherwise the browser silently refuses the file. -->
<script src="${URL_HINT}?v=${ver}" integrity="sha384-${sha384}" crossorigin="anonymous" async></script>
`);

writeFileSync(join(outDir, 'botanic-description.html'), description);

// Offline test page: the stand-in store page with the engine replaced by the embed and a
// SIMULATED Ecwid storefront API. It proves nothing about the real Ecwid. Options (query string):
//   ?pid=111      the simulated store reports another product
//   ?late=1       the store does NOT announce the page (the announcement "was missed")
//   ?noclass=1    the product-page class Ecwid puts on the page is removed
const stub = `<script>
/* SIMULATED Ecwid storefront API (tests only; not in the store). */
(function () {
  var q = location.search;
  var pid = Number((q.match(/pid=(\\d+)/) || [])[1]) || 876405767;
  var late = /late=1/.test(q);
  if (/noclass=1/.test(q)) {
    var pp = document.querySelector('.ecwid-productBrowser-ProductPage');
    if (pp) pp.className = 'ec-size ec-store';
  } else {
    var host = document.querySelector('.ecwid-productBrowser-ProductPage');
    if (host) host.className = host.className.replace(/ProductPage-\\d+/, 'ProductPage-' + pid);
  }
  var handlers = [];
  window.Ecwid = { OnPageLoaded: { add: function (fn) {
    handlers.push(fn);
    if (!late) setTimeout(function () { fn({ type: 'PRODUCT', productId: pid }); }, 50);
  } } };
  window.__ecwid = { fire: function (page) { handlers.slice().forEach(function (h) { h(page); }); } };
})();
</script>
<script src="botanic-tv.js"></script>`;
const test = read('prototype/template.html')
  .replace('/*ENGINE_CSS*/', () => '')
  .replace('<!--DESCRIPTION-->', () => description)
  .replace('<script>\n/*PRODUCT_CONFIG*/\n</script>\n<script>\n/*ENGINE_JS*/\n</script>\n<script>\n/*SCENES_JS*/\n</script>', () => stub)
  .replace('<script>DDTV.boot();</script>', () => '');
writeFileSync(join(outDir, 'test-page.html'), test);

const lines = [
  'Botanic Experience TV embed: generated files',
  `botanic-tv.js          ${embed.length} bytes   sha256 ${sha256hex}`,
  `                       sha384-${sha384}`,
  `cache-buster           ?v=${ver}`,
  '',
  'Loading order inside botanic-tv.js: ?ddtv=off check, font link, styles, product data (config + zones), engine, scenes, start when Ecwid\'s API exists.',
  'External dependency at run time: https://api.fontshare.com (Chillax font; the page still works without it).',
  'Media: absolute URLs under https://media.divinedunlop.com (videos, cover photos), as in the original description.',
  'Needs on the product page: the description with #bp-top (botanic-description.html) and Ecwid\'s options SIZE, Select Mattress Depth, FIRMNESS BY BODY WEIGHT, COVERS.',
];
writeFileSync(join(outDir, 'MANIFEST.txt'), lines.join('\n') + '\n');
