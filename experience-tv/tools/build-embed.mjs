// Builds the files for a real store test (Ecwid product page):
//
//   dist/embed/botanic-tv.js          one self-starting file; upload it to the web host
//   dist/embed/ecwid-snippet.html     the one line to paste into the store
//   dist/embed/botanic-description.html  the product description to paste into the product
//   dist/embed/test-page.html         the same page with an Ecwid stub, to check the embed offline
//
//   node tools/build-embed.mjs
//
// The embed does nothing on other products: the engine starts only for a
// product id listed in products/botanic.config.js (productIds).
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (p) => readFileSync(join(root, p), 'utf8');
const outDir = join(root, 'dist', 'embed');
mkdirSync(outDir, { recursive: true });

const css = read('engine/ddtv-engine.css') + '\n' + read('engine/ddtv-scenes.css');
const config = read('products/botanic.config.js');
const zones = read('products/botanic.zones.js');
const engine = read('engine/ddtv-engine.js');
const scenes = read('engine/ddtv-scenes.js');
const description = read('source/botanic-original-description.html');

// The embed. It injects the styles and the Chillax font, loads the product
// data and the engine, and starts once Ecwid's storefront API is available.
const embed = `/* Botanic Experience TV: store embed (generated by tools/build-embed.mjs).
   Starts only on the products listed in its config. Leave the store's own
   options, price and checkout untouched. */
(function () {
  if (window.__ddtvEmbedLoaded) return;
  window.__ddtvEmbedLoaded = true;

  var CSS = ${JSON.stringify(css)};
  var head = document.head || document.getElementsByTagName('head')[0] || document.documentElement;

  function add(tag, attrs) {
    var node = document.createElement(tag);
    for (var k in attrs) node.setAttribute(k, attrs[k]);
    head.appendChild(node);
    return node;
  }

  if (!document.getElementById('ddtv-font')) {
    add('link', { rel: 'preconnect', href: 'https://api.fontshare.com' });
    add('link', { id: 'ddtv-font', rel: 'stylesheet', href: 'https://api.fontshare.com/v2/css?f[]=chillax@300,400,500,600,700&display=swap' });
  }
  var style = document.getElementById('ddtv-styles') || add('style', { id: 'ddtv-styles' });
  style.textContent = CSS;

  /* ---- product data (botanic.config.js + botanic.zones.js) ---- */
${config}
${zones}

  /* ---- engine ---- */
${engine}

  /* ---- scenes ---- */
${scenes}

  /* ---- start once Ecwid's storefront API is there (about 15 s at most) ---- */
  var tries = 0;
  (function wait() {
    if (window.Ecwid && window.Ecwid.OnPageLoaded && window.DDTV) { window.DDTV.boot(); return; }
    if (++tries < 150) setTimeout(wait, 100);
  })();
})();
`;
writeFileSync(join(outDir, 'botanic-tv.js'), embed);

// Subresource Integrity: the browser refuses the file if it was changed after this build.
const hash = createHash('sha384').update(embed).digest('base64');
const snippet = `<!-- Botanic Experience TV: paste this ONE line into the store (see the notes).
     Replace the address with the place where botanic-tv.js is uploaded.
     If you re-upload a new build, use the new snippet too (the hash changes). -->
<script src="https://YOUR-SITE.example/PATH/botanic-tv.js" integrity="sha384-${hash}" crossorigin="anonymous" defer></script>
`;
writeFileSync(join(outDir, 'ecwid-snippet.html'), snippet);

writeFileSync(join(outDir, 'botanic-description.html'), description);

// Offline test: the prototype page with the engine replaced by the embed, and
// an Ecwid stub that reports product 876405767 (or ?pid=… to test another one).
const stub = `<script>
/* Test stub for Ecwid's storefront API (not in the store). */
window.Ecwid = { OnPageLoaded: { add: function (fn) {
  var pid = Number((location.search.match(/pid=(\\d+)/) || [])[1]) || 876405767;
  setTimeout(function () { fn({ type: 'PRODUCT', productId: pid }); }, 50);
} } };
</script>
<script src="botanic-tv.js"></script>`;
let test = read('prototype/template.html')
  .replace('/*ENGINE_CSS*/', () => '')
  .replace('<!--DESCRIPTION-->', () => description)
  .replace('<script>\n/*PRODUCT_CONFIG*/\n</script>\n<script>\n/*ENGINE_JS*/\n</script>\n<script>\n/*SCENES_JS*/\n</script>', () => stub)
  .replace('<script>DDTV.boot();</script>', () => '');
writeFileSync(join(outDir, 'test-page.html'), test);

console.log(`Wrote ${join(outDir, 'botanic-tv.js')} (${(embed.length / 1024).toFixed(1)} KB)`);
console.log(`Wrote ${join(outDir, 'ecwid-snippet.html')}, botanic-description.html, test-page.html`);
