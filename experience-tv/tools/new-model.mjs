// Scaffolds a new product model (the first step of docs/ONBOARDING-NEW-MODEL.md).
//
//   node tools/new-model.mjs <id> --name "BIO COMFORT" --product-id 123456789 [--dry-run] [--root dir]
//
// <id>           lowercase letters, digits and dashes (it becomes the file names and the config key)
// --product-id   the Ecwid id of the TEST product to run on. A live product id is refused: nothing may be pointed at a
//                live product before it is approved.
//
// It writes, and never overwrites:
//   products/<id>.config.js        a minimal, VALID model config that extends the store profile
//   products/<id>.assets.js        an empty Visual Asset Registry
//   source/<id>-description.html   a stub description with the markup the config's selectors point at
// and adds the model to products/models.json (status "development", deployment "not-authorised"). It then runs the
// validator. What you do next is on the checklist the tool prints. Nothing is invented: every text it writes says TODO.
import { createRequire } from 'node:module';
import { existsSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const args = process.argv.slice(2);
const id = args[0];
const flag = (n) => { const i = args.indexOf('--' + n); return i >= 0 ? args[i + 1] : undefined; };
const name = flag('name'), pid = Number(flag('product-id')), dry = args.includes('--dry-run');
const fail = (m) => { console.error('new-model: ' + m); process.exit(2); };
if (!id || !/^[a-z][a-z0-9-]*$/.test(id)) fail('usage: node tools/new-model.mjs <id> --name "NAME" --product-id N [--dry-run]   (id: lowercase letters, digits, dashes)');
if (!name) fail('--name is required');
if (!Number.isInteger(pid) || pid <= 0) fail('--product-id must be the Ecwid id of the TEST product');

const dataRoot = flag('root') ? resolve(flag('root')) : root;     // where the model's files are written (default: this repository)
const indexFile = join(dataRoot, 'products', 'models.json');
const index = JSON.parse(readFileSync(indexFile, 'utf8'));
if (index.some((m) => m.id === id)) fail(`a model "${id}" already exists`);
const live = index.flatMap((m) => (m.ecwid && m.ecwid.live) || []);
if (live.includes(pid)) fail(`product ${pid} is a LIVE product: a new model may only be pointed at a test product`);
const claimed = index.find((m) => (((m.ecwid || {}).test || []).includes(pid)));
if (claimed) fail(`product ${pid} is already the test product of "${claimed.id}"`);

const files = { config: `products/${id}.config.js`, assets: `products/${id}.assets.js`, source: `source/${id}-description.html` };
for (const f of Object.values(files)) if (existsSync(join(dataRoot, f))) fail(`${f} already exists: refusing to overwrite`);
const P = id.replace(/[^a-z0-9]/g, '');       // markup prefix for the stub

const config = `/*
 * Divine DunlopDreams — Experience TV
 * Model configuration: ${name}
 *
 * STATUS: development. Generated by tools/new-model.mjs. Every text below says TODO: nothing here is approved content.
 * Only what is specific to THIS model belongs in this file; layout, price and gallery selectors come from the store
 * profile ('divine-store'), and the screens come from the scene library. Do not copy another model's chapters, options,
 * values or visuals: a model keeps its own verified technical identity (docs/ARCHITECTURE-MULTI-MODEL.md, section 15).
 */
(function (global) {
  'use strict';
  global.DDTV_PRODUCTS = global.DDTV_PRODUCTS || {};

  global.DDTV_PRODUCTS[${JSON.stringify(id)}] = {
    id: ${JSON.stringify(id)},
    name: ${JSON.stringify(name)},
    status: 'development',
    extends: 'divine-store',

    /* The Ecwid TEST product this model may run on. A live product is added only after explicit approval. */
    productIds: [${pid}],
    sourceRoot: '#${P}-top',

    /* TODO: the options this model really has (size, firmness, height, cover, …), their kinds and values. Empty on
       purpose: no option is assumed. Each entry: { label, match: /title/i, chapter, panel, kind } */
    options: {},
    values: {},

    chapters: [
      {
        id: 'overview', label: 'Overview', source: '#${P}-overview',
        panels: [
          { id: 'intro', label: 'Introduction', scene: 'hero', dark: true, params: {
              kicker: '#${P}-overview .${P}-kicker', brand: '#${P}-overview .${P}-brand', headline: '#${P}-overview .${P}-h1',
              intro: '#${P}-overview .${P}-intro', actions: '#${P}-overview .${P}-btns a', note: '#${P}-overview .${P}-rule' } }
        ]
      }
    ],

    /* TODO: this description's own markup, if it differs from the house markup (see DDTV.dialect). */
    dialect: {},

    notInTelevision: [],
    media: []
  };
})(window);
`;
const assets = `/* Visual Asset Registry for "${id}". Data about assets; Ecwid owns the photographs. Empty until approved assets are added.
   Never type an address: copy it from Ecwid (tools/media-manifest.mjs, tools/asset-registry.mjs). */
(function (global) {
  'use strict';
  global.DDTV_ASSETS = global.DDTV_ASSETS || {};
  global.DDTV_ASSETS[${JSON.stringify(id)}] = { version: 1, galleryOrder: 'ecwid', assets: [] };
})(window);
`;
const source = `<!-- STUB for "${name}". TODO: replace with the model's own approved description. Nothing here is approved content. -->
<div id="${P}-top">
  <section id="${P}-overview">
    <div class="${P}-kicker">TODO kicker</div>
    <div class="${P}-brand">${name}</div>
    <h1 class="${P}-h1">TODO headline</h1>
    <p class="${P}-intro">TODO: approved introduction.</p>
    <div class="${P}-btns"><a href="#${P}-overview">TODO action</a></div>
    <p class="${P}-rule">TODO note</p>
  </section>
</div>
`;
const entry = { id, name, status: 'development', config: files.config, assets: files.assets, source: files.source, profile: 'products/profiles/divine-store.profile.js', ecwid: { test: [pid], live: [] }, deployment: 'not-authorised', production: false };

if (dry) { console.log('Would write:\n  ' + Object.values(files).join('\n  ') + `\nand add to products/models.json:\n${JSON.stringify(entry)}`); process.exit(0); }
// Everything is prepared above; now write. Directories first, the index last, so a failure never leaves an index entry
// pointing at files that were not written.
for (const f of Object.values(files)) mkdirSync(dirname(join(dataRoot, f)), { recursive: true });
writeFileSync(join(dataRoot, files.config), config);
writeFileSync(join(dataRoot, files.assets), assets);
writeFileSync(join(dataRoot, files.source), source);
index.push(entry);
writeFileSync(indexFile, JSON.stringify(index, null, 2) + '\n');
console.log(`Created ${Object.values(files).join(', ')} and added "${id}" to products/models.json (production: false until you set it).`);

const r = spawnSync(process.execPath, [join(root, 'tools', 'validate-model.mjs'), id, '--root', dataRoot], { encoding: 'utf8' });
process.stdout.write(r.stdout);
console.log(`
Next (docs/ONBOARDING-NEW-MODEL.md):
  1. Replace the stub description with the model's approved description.        2. Define its real options and values.
  3. Add its chapters and panels (scenes from the library).                        4. Add approved assets to products/${id}.assets.js.
  5. NODE_PATH=$(npm root -g) node tools/validate-model.mjs ${id} --source-check   6. Run the compatibility tests.
  7. Review the visual presentation.  8. Ask for approval. Set "production": true and the live product id only after it.`);
process.exit(r.status || 0);
