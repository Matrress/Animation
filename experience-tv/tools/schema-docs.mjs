// Writes docs/SCHEMA-REFERENCE.md from the schema definitions (schema/ddtv-schema.js), so the reference cannot drift
// from what the validator enforces. A test fails if the checked-in file differs from a fresh one.
//
//   node tools/schema-docs.mjs [--check]        (--check: print nothing, exit 1 if docs/SCHEMA-REFERENCE.md is stale)
import { createRequire } from 'node:module';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(import.meta.url);
const { specs, ENUM } = require(join(root, 'schema', 'ddtv-schema.js'));

const rows = [];
function walk(spec, path, depth) {
  if (!spec) return;
  const t = spec.type === 'array' ? 'array' : spec.type === 'map' ? 'map' : spec.type;
  const notes = [];
  if (spec.enum) notes.push('one of ' + spec.enum.map((x) => '`' + x + '`').join(', '));
  if (spec.pattern) notes.push('matches `' + spec.pattern.source + '`');
  if (spec.min) notes.push('at least ' + spec.min);
  if (spec.doc) notes.push(spec.doc);
  if (path) rows.push({ path, type: t, required: !!spec.required, notes: notes.join('; ') });
  if (spec.type === 'object' && spec.props) for (const k of Object.keys(spec.props)) walk(spec.props[k], path ? path + '.' + k : k, depth + 1);
  if (spec.type === 'array' && spec.items && (spec.items.type === 'object')) walk(spec.items, path + '[]', depth + 1);
  if (spec.type === 'array' && spec.items && spec.items.type !== 'object') { /* scalar items are described by the parent row */ }
  if (spec.type === 'map' && spec.of && spec.of.type === 'object') walk(spec.of, path + '.<key>', depth + 1);
  if (spec.type === 'map' && spec.of && spec.of.type === 'array') walk(spec.of, path + '.<key>', depth + 1);
}

const titles = {
  MODEL: ['Product model configuration', 'products/<model>.config.js: `window.DDTV_PRODUCTS.<id> = { … }`. Unknown top-level keys are warnings; a model may also `extends` a store profile.'],
  ASSET_REGISTRY: ['Visual Asset Registry', 'products/<model>.assets.js: `window.DDTV_ASSETS.<id> = { … }`. Data about assets; Ecwid owns the photographs.'],
  VISUAL_REF: ['Contextual visual (inside a topic)', 'A reference from a topic to an asset in the registry. `when` ties it to a value the customer has chosen.'],
  TOPIC: ['Topic', 'Declared in a model config (`topics`). Every panel is also a topic without declaring it.'],
  MODELS_INDEX: ['Models index', 'products/models.json: which models exist, their status, where they may run, whether they are authorised.']
};
let md = `# Schema reference

> Generated by \`node tools/schema-docs.mjs\` from \`schema/ddtv-schema.js\`. Do not edit by hand: a test fails when this file is stale.
> It lists what the validator (\`tools/validate-model.mjs\`) enforces structurally. The semantic rules (a scene must exist, an option must point at a screen that exists, a model must not claim another model's visuals, a live product must not be listed before approval) are in \`docs/ARCHITECTURE-MULTI-MODEL.md\`, sections 9 and 14.

Types: \`string\`, \`number\`, \`integer\`, \`boolean\`, \`array\`, \`object\`, \`map\` (an object whose values all follow one description), \`regexp\`, \`function\`, \`any\`. "Required" means the key must be present.

## Vocabularies

| Name | Values |
|---|---|
${Object.keys(ENUM).map((k) => `| \`${k}\` | ${ENUM[k].map((x) => '`' + x + '`').join(', ')} |`).join('\n')}
`;
for (const key of ['MODEL', 'ASSET_REGISTRY', 'ASSET', 'TOPIC', 'VISUAL_REF', 'MODELS_INDEX']) {
  rows.length = 0;
  const spec = specs[key];
  const [title, intro] = titles[key] || ['Asset', 'One entry of `assets` in a registry.'];
  if (spec.type === 'array') walk(spec.items, '[]', 0); else walk(spec, '', 0);
  md += `\n## ${title}\n\n${intro}\n\n| Key | Type | Required | Notes |\n|---|---|---|---|\n` + rows.map((r) => `| \`${r.path}\` | ${r.type} | ${r.required ? 'yes' : ''} | ${r.notes.replace(/\|/g, '\\|')} |`).join('\n') + '\n';
}
const out = join(root, 'docs', 'SCHEMA-REFERENCE.md');
if (process.argv.includes('--check')) {
  let cur = ''; try { cur = readFileSync(out, 'utf8'); } catch (e) { /* missing */ }
  process.exit(cur === md ? 0 : 1);
}
writeFileSync(out, md);
console.log('Wrote docs/SCHEMA-REFERENCE.md');
