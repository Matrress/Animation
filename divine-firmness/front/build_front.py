#!/usr/bin/env python3
"""Build the compact front-page firmness block from the verified /firmnesses sections.

Reads  divine-firmness/release/1.0.0-inline/*.html
Writes divine-firmness/front/release/<VER>/front.css, front.js
       divine-firmness/front/ecwid/tile-A-<VER>.html   (heading + monitor)   [dev urls]
       divine-firmness/front/ecwid/tile-B-<VER>.html   (cards + loader)      [dev urls]
With --sha <40 hex> it also writes the *-pinned.html tiles whose urls are locked to that commit on jsDelivr.

Only four parts of the module go to the front page: the monitor, the weight/height card,
the regulation card and the first / second choice. Everything else is replaced by hidden stubs
so the verified JS runs unchanged.
"""
import re, sys, os, argparse

VER = '0.1.0'
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
SRC = os.path.join(ROOT, 'release', '1.0.0-inline')
OUT = os.path.join(HERE, 'release', VER)
ECW = os.path.join(HERE, 'ecwid')
REPO = 'Matrress/Animation'
FONT = 'https://cdn.jsdelivr.net/gh/Matrress/Animation@f727e88417fd562938847735378af9a167e96034/divine-hero/release/1.20.2/assets/'
FORM_LINK = 'https://divinedunlop.com/firmnesses'


def rd(n):
    return open(os.path.join(SRC, n), encoding='utf8').read()


def styles(s):
    return re.findall(r'<style[^>]*>(.*?)</style>', s, re.S)


def scripts(s):
    return [m for m in re.findall(r'<script([^>]*)>(.*?)</script>', s, re.S)]


def must(cond, msg):
    if not cond:
        sys.exit('BUILD ERROR: ' + msg)


# ---------------------------------------------------------------- CSS
def build_css():
    c01 = styles(rd('01_CSS_module.html'))
    c02 = styles(rd('02_CSS_visual.html'))
    s03 = rd('03_Markup_intro_visual.html')
    s04 = rd('04_Markup_zone_texts.html')
    s05 = rd('05_Markup_module.html')
    must(len(c01) == 1 and len(c02) == 1, 'css sections changed shape')
    st04 = styles(s04)
    must(len(st04) == 5, '04 style blocks changed: %d' % len(st04))
    keep04 = [b for b in st04 if '.dnchk' not in b[:60]]          # drop the page-check banner style
    must(len(keep04) == 4, '04 keep blocks %d' % len(keep04))
    fonts = ('@font-face{font-family:DDVChillax;src:url(%schillax-400.woff2) format("woff2");font-weight:400;font-style:normal;font-display:swap}'
             '@font-face{font-family:DDVChillax;src:url(%schillax-600.woff2) format("woff2");font-weight:600;font-style:normal;font-display:swap}') % (FONT, FONT)
    front = (
        '/* front block: nothing may change the scale from outside; hidden until the script has fitted it */'
        '#ddv,#ddv-sec,#dn{zoom:1!important}'
        'html.ddv-wait:not(.ddv-fit) #ddv-sec,html.ddv-wait:not(.ddv-fit) #dn{visibility:hidden}'
        '#ddv[data-sw]{display:flex;flex-direction:column;justify-content:center}'
        '#ddv[data-sw] .ddv-stage{width:min(100%,var(--ddv-sw))!important}'
        '#dn .dn-ra a{justify-content:space-between!important}'
        '/* the hint "More below" becomes a real link on the front page */'
        '#dn .dn-body::after{content:none!important}'
        '#dn .fq-more{display:block;margin-top:10px;padding-top:8px;border-top:1px solid rgba(126,136,135,.5);font-size:12.5px;letter-spacing:.03em;color:var(--t2);text-align:center;text-decoration:none}'
        '#dn .fq-more:hover,#dn .fq-more:focus-visible{color:#fff;text-decoration:underline}'
    )
    # noscript fallback style of the monitor stays in the markup tile (it must sit inside <noscript>)
    css = '/* Divine DunlopDreams · Firmness front block %s · generated by front/build_front.py */\n' % VER
    css += fonts + '\n' + c01[0] + '\n' + c02[0] + '\n' + '\n'.join(keep04) + '\n' + front + '\n'
    return css


# ---------------------------------------------------------------- JS
def build_js():
    eng = scripts(rd('08_Logic.html'))
    must(len(eng) == 1, 'engine section changed shape')
    mod = scripts(rd('09_JS_module.html'))
    must(len(mod) == 2, '09 changed shape (banner + module expected)')
    vis = scripts(rd('10_JS_visual.html'))
    must(len(vis) == 1, '10 changed shape')
    s05 = scripts(rd('05_Markup_module.html'))
    fit = [b for a, b in s05 if 'type="application/ld+json"' not in a]
    must(len(fit) == 1, '05 fit script not found')
    parts = [('engine', eng[0][1]), ('module', mod[1][1]), ('scene', vis[0][1]), ('fit', fit[0])]
    out = '/* Divine DunlopDreams · Firmness front block %s · engine + module + scene + fit · generated by front/build_front.py */\n' % VER
    for nm, body in parts:
        must('</script' not in body, nm + ' contains </script')
        out += '/* ---- %s ---- */\n(function(){\n%s\n})();\n' % (nm, body.strip())
    return out


# ---------------------------------------------------------------- markup tiles
OLD_P = "Your weight and height set the regulation. Six short answers choose the latex mattress or topper. Then you see why it is right, and send us your selection."
NEW_P = "Need advice on firmness? Your weight and height set the regulation. You see your Dunlop firmness and the two latex models that fit you, with links straight to the products."


def tile_a(css_url):
    s03 = rd('03_Markup_intro_visual.html')
    i = s03.index('<section class="dn dn-a">')
    body = s03[i:]
    must(OLD_P in body, 'heading text not found in 03')
    body = body.replace(OLD_P, NEW_P)
    # notice placed OUTSIDE the monitor window, between the heading and the monitor
    notice = ('<div class="dn-w"><p class="fq-notice" style="margin:0 0 14px;font-size:13px;line-height:1.5;letter-spacing:.02em;text-align:center;color:var(--t2,#B8C2C0)">'
              '<b style="color:#fff">This is not an animation.</b> These are Dunlop regulations, based on engineering research.</p></div>')
    must('<section class="dn dn-b"' in body, 'monitor section not found in tile A')
    body = body.replace('<section class="dn dn-b"', notice + '<section class="dn dn-b"', 1)
    head = ('<!-- Divine DunlopDreams Firmness front block %s · tile A of 2: heading + monitor · paste first, right after the collection tile -->'
            '<link rel="stylesheet" href="%s">'
            "<script>(function(h){h.classList.add('ddv-wait');setTimeout(function(){h.classList.add('ddv-fit')},5000)})(document.documentElement)</script>") % (VER, css_url)
    return head + body


STUBS = ('<div hidden id="fq-stubs" aria-hidden="true">'
         '<div class="dn-pin" id="dn-pin"><i id="dn-pin-c"></i><b id="dn-pin-t"></b><span id="dn-pin-s"></span></div>'
         '<ul id="dn-v"></ul><span id="dn-v-t"></span><div id="dn-dens"></div><div id="dn-mixes"></div><ul id="dn-sel"></ul><div id="dn-picks"></div>'
         '<a id="dn-buy" href="#"></a><button type="button" id="dn-ask"></button><details id="dn-ct"></details>'
         '<form id="dn-form"><input id="dn-fn"><input id="dn-fp"><input id="dn-fe"><textarea id="dn-fq"></textarea><p id="dn-fm"></p></form>'
         '<div id="dn-qs"></div>'
         '<section id="ddv-spec" data-mode="explore"><dl><dd id="ddv-e1"></dd><dd id="ddv-e2"></dd><dd id="ddv-e3"></dd><dd id="ddv-e4"></dd></dl></section>'
         '</div>')


def tile_b(js_url):
    s05 = rd('05_Markup_module.html')
    s04 = rd('04_Markup_zone_texts.html')
    a = s05.index('<div class="dn-w">')
    row0 = s05.index('<div class="dn-row">')
    row1 = s05.index('<p class="dn-act"><b>2</b>')
    act = s05[a:row0]                       # <div class="dn-w">  <p class="dn-act">1 ...</p>
    row = s05[row0:row1]                    # the two cards (+ nothing else) – ends with </div> of the row
    must(row.rstrip().endswith('</div>'), 'row boundary')
    # the link that replaces the "More below" hint: last child of the left card
    marker = '<div class="dn-card dn-ans"'
    k = row.index(marker)
    left = row[:k]
    must(left.rstrip().endswith('</div>'), 'left card end')
    left = left.rstrip()[:-len('</div>')] + '<a class="fq-more" href="%s">Fine-tune with six quick answers · full details →</a></div>' % FORM_LINK
    row = left + row[k:]
    zx = re.search(r'<div class="ddv-x" id="ddv-x">.*?</div>(?=<style)', s04, re.S)
    must(zx is not None, 'zone texts not found')
    sect = '<section class="dn dn-c" id="dn">' + STUBS + act + row + '</div></section>'
    loader = ("<script>(function(){var d=document,s=d.createElement('script');s.src='%s';s.defer=true;"
              "s.onerror=function(){d.documentElement.classList.add('ddv-fit')};d.head.appendChild(s)})();</script>") % js_url
    return ('<!-- Divine DunlopDreams Firmness front block %s · tile B of 2: cards + points text + loader · paste second, right after tile A -->' % VER) + sect + zx.group(0) + loader


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--sha')
    a = ap.parse_args()
    os.makedirs(OUT, exist_ok=True)
    os.makedirs(ECW, exist_ok=True)
    css, js = build_css(), build_js()
    open(os.path.join(OUT, 'front.css'), 'w', encoding='utf8').write(css)
    open(os.path.join(OUT, 'front.js'), 'w', encoding='utf8').write(js)
    base = 'https://cdn.jsdelivr.net/gh/%s@%%s/divine-firmness/front/release/%s/' % (REPO, VER)
    dev = 'front.css'
    open(os.path.join(ECW, 'tile-A-%s.html' % VER), 'w', encoding='utf8').write(tile_a('front.css'))
    open(os.path.join(ECW, 'tile-B-%s.html' % VER), 'w', encoding='utf8').write(tile_b('front.js'))
    print('front.css', len(css), 'bytes | front.js', len(js), 'bytes')
    ta, tb = tile_a('front.css'), tile_b('front.js')
    if a.sha:
        must(re.fullmatch(r'[0-9a-f]{40}', a.sha), 'sha must be 40 hex')
        b = base % a.sha
        pa, pb = tile_a(b + 'front.css'), tile_b(b + 'front.js')
        open(os.path.join(ECW, 'tile-A-%s-pinned.html' % VER), 'w', encoding='utf8').write(pa)
        open(os.path.join(ECW, 'tile-B-%s-pinned.html' % VER), 'w', encoding='utf8').write(pb)
        ta, tb = pa, pb
    for nm, t in (('tile A', ta), ('tile B', tb)):
        flag = '' if len(t) <= 19900 else '  <-- TOO BIG'
        hexes = len(re.findall(r'\\x[0-9a-fA-F]{2}', t))
        print('%s: %d chars%s | \\xNN: %d' % (nm, len(t), flag, hexes))


if __name__ == '__main__':
    main()
