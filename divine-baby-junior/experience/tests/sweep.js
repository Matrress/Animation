/* Screenshots of every state of the Baby Experience on the Ecwid imitation. node experience/tests/sweep.js OUTDIR */
const { chromium, devices } = require('playwright'); const path = require('path');
const out = process.argv[2] || 'docs/shots';
const tv = 'file://' + path.resolve(__dirname, '../harness/tv.html'), ph = 'file://' + path.resolve(__dirname, '../harness/phone.html');
(async () => {
  const b = await chromium.launch();
  const ctx = await b.newContext({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'reduce' }); const p = await ctx.newPage();
  const errs = []; p.on('pageerror', e => errs.push(e.message));
  await p.goto(tv); await p.waitForSelector('#ddtv-experience'); await p.waitForTimeout(1200);
  const host = await p.$('#ddtv-experience'); const snap = async n => { await host.screenshot({ path: out + '/x-' + n + '.png' }); };
  await snap('1-start');
  await p.click('[data-topic="size"]'); await p.click('[data-part="2"]'); await p.waitForTimeout(300); await snap('2-sizes-junior');
  await p.click('[data-topic="height"]'); await p.waitForTimeout(300); await snap('3-height');
  await p.click('[data-topic="cover"]'); await p.waitForTimeout(300); await snap('4-cover');
  await p.click('[data-topic="order"]'); await p.click('[data-part="1"]'); await p.waitForTimeout(300); await snap('5-prices-empty');
  await p.click('#galbtn'); await p.waitForTimeout(300); await snap('6-buy-size');
  await p.click('[data-family="junior"]'); await p.click('[data-pick-size="80x180"]'); await p.waitForTimeout(500); await snap('7-buy-size-picked');
  await p.click('[data-next="height"]'); await p.waitForTimeout(1500); await snap('8-buy-height');
  await p.click('[data-pick-height="14"]'); await p.waitForTimeout(2500); await snap('9-buy-height-picked');
  await p.click('[data-next="firmness"]'); await p.waitForTimeout(300); await snap('10-buy-firmness');
  await p.click('[data-next="cover"]'); await p.click('[data-next="review"]'); await p.waitForTimeout(400); await snap('11-review');
  await p.click('#allbtn'); await p.waitForTimeout(300); await snap('12-all');
  await p.keyboard.press('Escape');
  await p.click('[data-view="std"]'); await p.waitForTimeout(600); await p.screenshot({ path: out + '/x-13-standard.png', fullPage: false });
  console.log('desktop errors', errs);
  await ctx.close();
  const c2 = await b.newContext({ viewport: { width: 834, height: 1100 }, reducedMotion: 'reduce' }); const p2 = await c2.newPage();
  await p2.goto(tv); await p2.waitForSelector('#ddtv-experience'); await p2.waitForTimeout(1200);
  await (await p2.$('#ddtv-experience')).screenshot({ path: out + '/x-20-ipad.png' });
  await p2.click('#galbtn'); await p2.waitForTimeout(300); await (await p2.$('#ddtv-experience')).screenshot({ path: out + '/x-21-ipad-buy.png' });
  await c2.close();
  const c3 = await b.newContext({ ...devices['iPhone 13'], reducedMotion: 'reduce' }); const p3 = await c3.newPage();
  await p3.goto(ph); await p3.waitForSelector('#ddp-cta'); await p3.waitForTimeout(800);
  await p3.locator('#ddp-cta').scrollIntoViewIfNeeded(); await p3.screenshot({ path: out + '/x-30-phone-cta.png' });
  await p3.click('#ddp-cta'); await p3.waitForTimeout(400); await p3.screenshot({ path: out + '/x-31-phone-size.png' });
  await p3.click('[data-family="cot"]'); await p3.click('[data-pick-size="60x120"]'); await p3.waitForTimeout(300); await p3.screenshot({ path: out + '/x-32-phone-size-picked.png' });
  await p3.click('[data-go="height"]'); await p3.waitForTimeout(300); await p3.click('[data-pick-height="10"]'); await p3.waitForTimeout(2500); await p3.screenshot({ path: out + '/x-33-phone-height.png' });
  await p3.click('[data-go="review"]'); await p3.waitForTimeout(500); await p3.screenshot({ path: out + '/x-34-phone-review.png' });
  await b.close();
})();
