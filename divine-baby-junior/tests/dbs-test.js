const { chromium, devices } = require('playwright'); const path = require('path');
const file = 'file://' + path.resolve(process.argv[2]); const out = process.argv[3];
let fails = 0; const ok = (c, m) => { console.log((c ? 'PASS ' : 'FAIL ') + m); if (!c) fails++; };
(async () => {
  const b = await chromium.launch();
  const ctx = await b.newContext({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'reduce' });
  const p = await ctx.newPage(); const errs = []; p.on('pageerror', e => errs.push(e.message)); p.on('console', m => { if (m.type() === 'error') errs.push(m.text()); });
  await p.goto(file); await p.waitForSelector('.dbs--on', { timeout: 8000 }).catch(() => {});
  ok(await p.$('.dbs--on') !== null, 'selector upgraded (dbs--on)');
  ok((await p.$$('.dbs-btn')).length === 2 + 8 + 3, 'all buttons created (2 types, 8 sizes, 3 heights)');
  ok(await p.evaluate(() => !!document.querySelector('.dbs[data-pending="true"]')), 'starts pending, nothing selected');
  ok(await p.evaluate(() => document.querySelector('.details-product-option--SIZE select').selectedIndex === 0), 'native size NOT changed on load');
  await p.click('.dbs-btn:has-text("Junior")');
  ok(await p.evaluate(() => document.querySelector('[data-sizes="junior"]').hidden === false && document.querySelector('[data-sizes="cot"]').hidden === true), 'Junior shows only junior sizes');
  await p.click('.dbs-btn:has-text("80 × 200 cm")');
  await p.click('.dbs-btn:has-text("14 cm")');
  const nat = await p.evaluate(() => ({ s: document.querySelector('.details-product-option--SIZE select').value, h: document.querySelector('.details-product-option--HEIGHT select').value, price: document.getElementById('proto-price').textContent }));
  ok(/80 × 200 cm/.test(nat.s), 'native SIZE set: ' + nat.s);
  ok(/14 cm/.test(nat.h), 'native HEIGHT set: ' + nat.h);
  await p.waitForTimeout(900);
  const sum = await p.evaluate(() => ({ v: document.querySelector('.dbs-sv').textContent, v2: document.querySelector('.dbs-sv2').textContent, st: document.querySelector('.dbs-st').textContent, price: document.querySelector('.dbs-price').textContent, pend: document.querySelector('.dbs').getAttribute('data-pending'), cta: !document.querySelector('.dbs-cta').hidden }));
  console.log('summary', JSON.stringify(sum));
  ok(/Junior · 80 × 200 cm · 14 cm/.test(sum.v) && /31\.5 × 78\.7 in · 5\.5 in/.test(sum.v2), 'summary shows cm and inches');
  ok(/Selected in the options/.test(sum.st), 'status: selected in the options');
  ok(sum.price === nat.price && /£\d+/.test(sum.price), 'price read from Ecwid: ' + sum.price);
  ok(sum.cta, 'Add to bag shown');
  await p.click('.dbs-cta');
  ok(await p.evaluate(() => document.getElementById('proto-add').getAttribute('data-clicked') === '1'), 'Add to bag proxies the native button');
  const labs = await p.evaluate(() => [...document.querySelectorAll('.dbs-lab')].map(l => l.textContent));
  console.log('labels', JSON.stringify(labs));
  ok(labs.some(t => /200 cm/.test(t) && /78\.7 in/.test(t)) && labs.some(t => /80 cm/.test(t) && /31\.5 in/.test(t)) && labs.some(t => /14 cm/.test(t) && /5\.5 in/.test(t)), 'drawing labels carry cm and inches');
  await p.click('.dbs-u[data-unit="in"]');
  ok(await p.evaluate(() => { const bt = document.querySelector('[data-w] .dbs-btn[aria-checked="true"]'); return getComputedStyle(bt.querySelector('.dbs-in')).order === '1'; }), 'inches first after toggle');
  await p.click('.dbs-u[data-unit="cm"]');
  await p.focus('.dbs-btn[aria-checked="true"]:has-text("80 × 200")');
  await p.keyboard.press('ArrowLeft');
  ok(await p.evaluate(() => document.querySelector('.details-product-option--SIZE select').value.includes('80 × 180')), 'ArrowLeft selects the previous size and syncs');
  await p.selectOption('.details-product-option--SIZE select', { label: 'Baby Cot · 70 × 130 cm · 27.6 × 51.2 in' });
  await p.waitForTimeout(200);
  ok(await p.evaluate(() => /Baby Cot · 70 × 130 cm/.test(document.querySelector('.dbs-sv').textContent)), 'follows the native dropdown (reverse sync)');
  await p.screenshot({ path: out + '/dbs-desktop.png', fullPage: false });
  const el = await p.$('.dbs'); await el.scrollIntoViewIfNeeded(); await el.screenshot({ path: out + '/dbs-panel.png' });
  ok(errs.length === 0, 'no console errors ' + errs.join('|'));
  const c2 = await b.newContext({ viewport: { width: 1440, height: 1000 }, javaScriptEnabled: false }); const p2 = await c2.newPage(); await p2.goto(file);
  ok((await p2.$$('.dbs-list li')).length === 13, 'without JS the static list stays (13 items)');
  const el2 = await p2.$('.dbs'); await el2.screenshot({ path: out + '/dbs-static.png' });
  const c3 = await b.newContext({ ...devices['iPhone 13'], reducedMotion: 'reduce' }); const p3 = await c3.newPage(); await p3.goto(file); await p3.waitForSelector('.dbs--on');
  await p3.tap('.dbs-btn:has-text("Baby Cot")'); await p3.tap('.dbs-btn:has-text("60 × 120 cm")'); await p3.tap('.dbs-btn:has-text("12 cm")');
  await p3.waitForTimeout(500);
  const ov = await p3.evaluate(() => document.documentElement.scrollWidth - innerWidth);
  ok(ov <= 0, 'phone: no horizontal overflow (' + ov + ')');
  const el3 = await p3.$('.dbs'); await el3.screenshot({ path: out + '/dbs-phone.png' });
  console.log(fails ? 'FAILURES: ' + fails : 'ALL PASSED'); await b.close();
})();
